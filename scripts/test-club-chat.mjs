import assert from 'node:assert/strict';
import ts from 'typescript';
import { readFileSync } from 'node:fs';
const source = ts.transpile(readFileSync('src/lib/clubChat.ts', 'utf8'), { target: ts.ScriptTarget.ES2023, module: ts.ModuleKind.ESNext });
const { planChat, selectChatMatches, parsePeriod, lisbonClock } = await import('data:text/javascript;base64,' + Buffer.from(source).toString('base64'));
const now = new Date('2026-10-19T12:00:00Z');
const ask = (text, ctx = {}) => planChat(text, ctx, now);
assert.equal(ask('Quando é o próximo jogo dos Seniores?').plan.intent, 'next');
assert.equal(ask('Jogos dos Juvenis este mês').plan.period.end, '2026-10-31');
assert.equal(ask('Meu filho tem 10 anos').context.awaitingYear, true);
assert.equal(ask('2016', { awaitingYear: true }).plan.year, '2016');
assert.equal(ask('2027', { awaitingYear: true }).plan.kind, 'reply');
assert.equal(ask('Qual a classificação dos Iniciados?').plan.intent, 'standings');
assert.deepEqual(ask('Jogos dos Benjamins').plan.choices, ['Benjamins A', 'Benjamins B']);
const ambiguous = ask('Jogos dos Benjamins este mês');
assert.equal(ask('Benjamins A', ambiguous.context).plan.period.start, '2026-10-01');
assert.equal(ask('e os Juvenis?', ask('Próximo jogo dos Seniores').context).plan.team, 'Juvenis');
assert.equal(ask('Jogos dos Seniores em janeiro de 2027').plan.period.start, '2027-01-01');
assert.equal(parsePeriod('proximo mes', '2026-12-31').end, '2027-01-31');
assert.equal(parsePeriod('este fim de semana', '2026-10-18').start, '2026-10-17');
assert.equal(lisbonClock(new Date('2026-10-18T23:30:00Z')).date, '2026-10-19');
assert.equal(ask('Jogos de ontem dos Seniores').plan.kind, 'reply');
assert.equal(ask('Próximos jogos dos Seniores').plan.intent, 'games');
assert.equal(ask('Jogos dos Juvenis no dia 24 de outubro').plan.kind, 'reply');
assert.equal(ask('Jogos dos Seniores e Juvenis').plan.kind, 'reply');
assert.equal(ask('Não quero os Seniores').plan.kind, 'reply');
assert.equal(ask('Qual é a receita de um bolo?', { intent: 'games', team: 'Seniores' }).plan.kind, 'reply');
const match = (id, date, status = 'agendado', extra = {}) => ({ id, match_date: date, status, is_visible: true, match_time: '15:00:00', ...extra });
const rows = [match('past', '2026-10-17'), match('today-past', '2026-10-19', 'agendado', { match_time: '09:00:00' }), match('future', '2026-10-25'), match('hidden', '2026-10-20', 'agendado', { is_visible: false }), match('archived', '2026-10-20', 'arquivado'), match('postponed', '2026-10-20', 'adiado'), match('result', '2026-10-18', 'terminado')];
assert.equal(selectChatMatches(rows, 'next', undefined, now)[0].id, 'future');
assert.deepEqual(selectChatMatches(rows, 'results', undefined, now).map(x => x.id), ['result']);
assert.equal(selectChatMatches(rows, 'games', parsePeriod('este mes', '2026-10-19'), now).length, 5);
assert.deepEqual(selectChatMatches(rows, 'next', parsePeriod('novembro', '2026-10-19'), now), []);
console.log('Chat: interpretação, ambiguidades, seguimento, datas de Lisboa, viragem de ano, visibilidade, arquivo e adiamentos validados.');
